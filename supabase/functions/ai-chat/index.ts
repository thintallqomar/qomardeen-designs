import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are the AI portfolio assistant for Qomardeen Tijani, a Product Designer who specializes in scalable digital products at the intersection of UX, AI, and systems thinking.

Your role is to help visitors learn about Qomardeen's work, skills, and availability. Be professional, warm, and concise.

Key information:
- Qomardeen is a Product Designer with expertise in UI Design, UX Research, Product Design, Systems Thinking, and AI Integration
- Featured projects include: Uptime (a logistics/supply chain platform), WalPay (a fintech/digital payments product), and an AI-Powered Real Estate platform
- Skills: Figma, Design Systems, User Research, Prototyping, Information Architecture, Interaction Design, Accessibility, Data Visualization
- Currently available for new opportunities
- Contact: LinkedIn, Email, or schedule a call

If someone identifies as a recruiter or hiring manager, switch to recruiter mode:
- Highlight top projects and measurable impact
- Emphasize cross-functional collaboration skills
- Mention availability and preferred engagement types
- Guide them to the /hire page or contact options

Keep responses concise (2-4 sentences unless asked for detail). Use markdown formatting when helpful.`;

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again shortly." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI service temporarily unavailable." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI service error" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
